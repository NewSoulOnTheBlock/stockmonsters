/* ================================================================== VIEW ===*/

const REGION_ORDER: RegionFilter[] = ['all', 'exchange', 'kanto', 'johto', 'other']

const tiles = (m: MapCatalogEntry) => m.width * m.height

let instance: MapBrowserApi | null = null

export function mountMapBrowser(engine?: EngineLike, socket?: SocketLike): MapBrowserApi {
  if (instance) return instance
  ensureUiKit()
  injectStyle('sm-mapbrowser-css', CSS)

  const byId = new Map(MAP_CATALOG.map((m) => [m.id, m]))
  let region: RegionFilter = 'all'
  let query = ''
  let sort: MapSortKey = 'name'
  let visible: MapCatalogEntry[] = []

  /* --- chrome ------------------------------------------------------------ */
  const root = el('div', {
    id: 'sm-mapbrowser', class: 'smui smui-win',
    role: 'dialog', 'aria-label': 'World map', 'aria-modal': 'false',
  })

  const titlebar = el('div', { class: 'smui-titlebar' })
  const countChip = el('span', { class: 'mb-count-chip' }, [
    el('span', { class: 'dot' }),
    el('span', { text: `${MAP_CATALOG.length} PLACES` }),
  ])
  const closeBtn = el('button', {
    class: 'smui-btn smui-close is-danger', type: 'button',
    'aria-label': 'Close world map', text: '✕',
  })
  titlebar.append(
    el('span', { class: 'title', text: 'WORLD MAP' }),
    el('span', { class: 'spacer' }),
    countChip,
    closeBtn,
  )

  /* --- sidebar ----------------------------------------------------------- */
  const search = el('input', {
    class: 'smui-input', type: 'search', placeholder: 'Search places…',
    'aria-label': 'Search maps', autocomplete: 'off', spellcheck: 'false',
  })
  guardKeys(search)
  let searchTimer: any = null
  search.addEventListener('input', () => {
    clearTimeout(searchTimer)
    searchTimer = setTimeout(() => { query = search.value.trim().toLowerCase(); refresh() }, 120)
  })

  const regionBtns = new Map<RegionFilter, HTMLButtonElement>()
  const regionList = el('div', { role: 'tablist', 'aria-label': 'Region' })
  for (const r of REGION_ORDER) {
    const label = r === 'all' ? 'All' : REGION_LABELS[r]
    const n = r === 'all' ? MAP_CATALOG.length : MAP_CATALOG.filter((m) => m.region === r).length
    const b = el('button', {
      class: `mb-region${r === 'all' ? ' is-on' : ''}`, type: 'button',
      role: 'tab', 'aria-selected': r === 'all' ? 'true' : 'false', 'data-region': r,
    }, [
      el('span', { class: 'sw', style: `background:${r === 'all' ? 'var(--sm-text)' : REGION_COLORS[r]}` }),
      el('span', { class: 'lb', text: label }),
      el('span', { class: 'n', text: String(n) }),
    ])
    b.addEventListener('click', () => setRegion(r))
    regionBtns.set(r, b)
    regionList.appendChild(b)
  }

  const side = el('div', { class: 'mb-side' }, [
    el('div', { class: 'mb-search' }, [search]),
    el('div', { class: 'mb-regions smui-scroll' }, [
      el('h5', { text: 'Region' }),
      regionList,
      el('div', {
        class: 'mb-hint',
        text: 'Pick a place to see its preview, size and the maps it borders. Travel is instant.',
      }),
    ]),
  ])

  /* --- main -------------------------------------------------------------- */
  const countEl = el('strong', { text: '—' })
  const sortSel = el('select', { class: 'smui-input', 'aria-label': 'Sort maps' })
  for (const [v, label] of [
    ['name', 'Name A-Z'], ['size-desc', 'Largest first'], ['size-asc', 'Smallest first'],
  ] as const) sortSel.appendChild(el('option', { value: v, text: label }))
  sortSel.addEventListener('change', () => { sort = sortSel.value as MapSortKey; refresh() })
  guardKeys(sortSel)

  const toolbar = el('div', { class: 'mb-toolbar' }, [
    countEl, el('span', { text: 'PLACES' }),
    el('span', { class: 'spacer' }),
    el('span', { text: 'SORT' }), sortSel,
  ])
  const grid = el('div', { class: 'mb-grid smui-scroll' })
  const main = el('div', { class: 'mb-main' }, [toolbar, grid])

  const body = el('div', { class: 'mb-body' }, [side, main])
  const modal = el('div', { class: 'mb-modal' })

  root.append(titlebar, body, modal)
  document.body.appendChild(root)
  makeDraggable(root, titlebar)

  /* --------------------------------------------------- lazy thumbnails --- */
  /*
   * 171 maps means 171 PNGs. Fetch one only when its card is near the viewport;
   * `rootMargin` gives the image a screenful of runway so it is usually decoded
   * by the time the player scrolls to it. Older engines with no
   * IntersectionObserver just load everything, which is the old behaviour and
   * still correct.
   */
  const io = typeof IntersectionObserver !== 'undefined'
    ? new IntersectionObserver((entries, obs) => {
      for (const e of entries) {
        if (!e.isIntersecting) continue
        const img = e.target as HTMLImageElement
        obs.unobserve(img)
        loadThumb(img)
      }
    }, { root: grid, rootMargin: '300px 0px' })
    : null

  function loadThumb(img: HTMLImageElement) {
    const src = img.dataset.src
    if (!src || img.getAttribute('src')) return
    img.addEventListener('load', () => img.classList.add('is-loaded'), { once: true })
    img.addEventListener('error', () => { img.remove() }, { once: true })
    img.setAttribute('src', src)
  }

  function thumbNode(m: MapCatalogEntry, eager = false): HTMLElement {
    const img = el('img', {
      alt: `${m.name} preview`, draggable: 'false', decoding: 'async', loading: 'lazy',
    }) as HTMLImageElement
    img.dataset.src = m.thumb
    if (eager || !io) loadThumb(img)
    else io.observe(img)
    return img
  }

  /* --------------------------------------------------------------- render */
  function regionChip(m: MapCatalogEntry): HTMLElement {
    return el('span', {
      class: 'chip',
      style: `background:${REGION_COLORS[m.region]}`,
      text: REGION_LABELS[m.region].toUpperCase(),
    })
  }

  function card(m: MapCatalogEntry): HTMLElement {
    const shot = el('div', { class: 'mb-shot' }, [
      el('span', { class: 'ph', text: '▦', 'aria-hidden': 'true' }),
      thumbNode(m),
      regionChip(m),
    ])
    const openBtn = el('button', {
      class: 'mb-open', type: 'button',
      'aria-label': `${m.name} — details`, title: m.name,
    }, [
      shot,
      el('span', { class: 'name', text: m.name }),
      el('span', { class: 'sub' }, [
        el('span', { text: `${m.width}×${m.height} TILES` }),
        m.connections.length ? el('span', { text: `⇄ ${m.connections.length}` }) : null,
      ]),
    ])
    openBtn.addEventListener('click', () => openDetail(m.id))

    const travel = el('button', { class: 'smui-btn is-primary', type: 'button', text: 'Travel' })
    travel.addEventListener('click', (e) => { e.stopPropagation(); doTravel(m) })

    return el('div', { class: 'mb-card' }, [openBtn, travel])
  }

  function compute(): MapCatalogEntry[] {
    const q = query
    const out = MAP_CATALOG.filter((m) => {
      if (region !== 'all' && m.region !== region) return false
      if (!q) return true
      return `${m.name} ${m.id} ${REGION_LABELS[m.region]}`.toLowerCase().includes(q)
    })
    if (sort === 'size-desc') out.sort((a, b) => tiles(b) - tiles(a) || a.name.localeCompare(b.name))
    else if (sort === 'size-asc') out.sort((a, b) => tiles(a) - tiles(b) || a.name.localeCompare(b.name))
    else out.sort((a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id))
    return out
  }

  function refresh() {
    visible = compute()
    countEl.textContent = String(visible.length)
    io?.disconnect()
    grid.textContent = ''
    if (!visible.length) {
      grid.appendChild(el('div', { class: 'mb-empty', text: 'NO PLACES MATCH THIS SEARCH' }))
      return
    }
    const frag = document.createDocumentFragment()
    for (const m of visible) frag.appendChild(card(m))
    grid.appendChild(frag)
  }

  function setRegion(r: RegionFilter) {
    region = r
    for (const [id, b] of regionBtns) {
      const on = id === r
      b.classList.toggle('is-on', on)
      b.setAttribute('aria-selected', String(on))
    }
    grid.scrollTop = 0
    refresh()
  }

  /* ---------------------------------------------------------- detail sheet */
  let releaseSheet: (() => void) | null = null

  function closeDetail() {
    modal.classList.remove('open')
    modal.textContent = ''
    releaseSheet?.()
    releaseSheet = null
  }

  function attrRow(k: string, v: Node | string): HTMLElement {
    return el('div', { class: 'r' }, [
      el('span', { class: 'k', text: k }),
      typeof v === 'string'
        ? el('span', { class: 'v', text: v, title: v })
        : el('span', { class: 'v' }, [v]),
    ])
  }

  function openDetail(id: string) {
    const m = byId.get(id)
    if (!m) return
    const wasOpen = !!releaseSheet
    modal.textContent = ''

    const links = el('div', { class: 'mb-links' })
    const neighbours = m.connections.map((c) => byId.get(c)).filter(Boolean) as MapCatalogEntry[]
    if (neighbours.length) {
      for (const n of neighbours) {
        const b = el('button', { class: 'mb-link', type: 'button', text: n.name })
        b.addEventListener('click', () => openDetail(n.id))
        links.appendChild(b)
      }
    } else {
      links.appendChild(el('span', {
        class: 'mb-note', style: 'border:none;padding:0',
        text: 'No recorded edge links — reachable by fast travel only.',
      }))
    }

    const attrs = el('div', { class: 'mb-attrs' }, [
      attrRow('REGION', REGION_LABELS[m.region]),
      attrRow('SIZE', `${m.width} × ${m.height} tiles (${m.width * 32} × ${m.height * 32} px)`),
      attrRow('MAP ID', m.id),
      attrRow('BORDERS', links),
    ])

    const travelBtn = el('button', { class: 'smui-btn is-primary', type: 'button', text: 'Travel here' })
    const cancelBtn = el('button', { class: 'smui-btn', type: 'button', text: 'Back' })

    const sheet = el('div', { class: 'sheet' }, [
      el('div', { class: 'head' }, [
        el('span', { class: 'title', text: 'FAST TRAVEL' }),
        el('span', { class: 'spacer' }),
      ]),
      el('div', { class: 'content smui-scroll' }, [
        el('div', { class: 'mb-bigshot' }, [thumbNode(m, true)]),
        el('div', { class: 'info' }, [
          el('h3', { text: m.name }),
          attrs,
          el('div', {
            class: 'mb-note',
            text: 'You arrive at this map\'s designated landing tile. The server picks the exact spot and refuses anywhere you are not allowed to be.',
          }),
        ]),
      ]),
      el('div', { class: 'foot' }, [
        el('div', { class: 'dest' }, [
          el('span', { class: 'k', text: 'DESTINATION' }),
          el('span', { class: 'v', text: m.name, title: m.name }),
        ]),
        el('span', { class: 'spacer' }),
        cancelBtn, travelBtn,
      ]),
    ])

    modal.appendChild(sheet)
    modal.classList.add('open')
    // Re-entering the sheet from a BORDERS link must not stack ESC layers.
    if (!wasOpen) releaseSheet = pushLayer(closeDetail)
    cancelBtn.addEventListener('click', closeDetail)
    travelBtn.addEventListener('click', () => doTravel(m))
    setTimeout(() => travelBtn.focus(), 0)
  }

  /* ---------------------------------------------------------------- travel */
  function doTravel(m: MapCatalogEntry) {
    engine?.processAction?.('travel:to', { map: m.id })
    close()
  }

  /* -------------------------------------------------------- open / close */
  let releaseWindow: (() => void) | null = null
  function open() {
    if (root.classList.contains('open')) return
    root.classList.add('open')
    releaseWindow = pushLayer(() => close())
    refresh()
    setTimeout(() => search.focus(), 0)
  }
  function close() {
    closeDetail()
    root.classList.remove('open')
    releaseWindow?.()
    releaseWindow = null
  }
  closeBtn.addEventListener('click', () => close())

  // Never fight the RPG-JS dialog layer: step aside while a dialog is up.
  const stopWatch = watchGameDialog((dialogOpen) => {
    root.classList.toggle('dialog-hidden', dialogOpen)
  })

  // Optional server push, harmless if the event never fires.
  socket?.on?.('map:browser', (d: { map?: string }) => {
    if (d?.map) api.show(d.map)
    else open()
  })

  const api: MapBrowserApi = {
    root,
    open,
    close,
    toggle() { root.classList.contains('open') ? close() : open() },
    isOpen: () => root.classList.contains('open'),
    show(mapId) { open(); openDetail(mapId) },
    destroy() {
      stopWatch()
      io?.disconnect()
      close()
      root.remove()
      instance = null
    },
  }
  instance = api
  return api
}

/** Open the world map, mounting it on first use. */
export function openMapBrowser(): MapBrowserApi {
  const api = instance ?? mountMapBrowser()
  api.open()
  return api
}

export function closeMapBrowser(): void { instance?.close() }
export function getMapBrowser(): MapBrowserApi | null { return instance }
