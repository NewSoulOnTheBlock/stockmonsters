/*
 * map-browser.ts — the in-game WORLD MAP / fast-travel window.
 *
 *   mountMapBrowser(engine, socket)   // create it (hidden) at boot
 *   openMapBrowser()                  // open it from anywhere (HUD MAP button)
 *
 * Structure — deliberately the marketplace's shape, so the two windows feel
 * like one program:
 *   ┌ titlebar (draggable) · place count · close ───────────────────────────┐
 *   │ sidebar: search + region list │ toolbar + card grid                   │
 *   └───────────────────────────────────────────────────────────────────────┘
 *   One sub-sheet overlays the window: the map detail / TRAVEL HERE panel,
 *   modelled on the marketplace's purchase sheet.
 *
 * Data comes from src/data/map-catalog.ts, generated by
 * tools/render-map-thumbs.mjs together with the preview PNGs in
 * public/mapthumbs/. There are 171 maps, so every thumbnail is fetched only
 * once its card scrolls into view (IntersectionObserver, below) — otherwise
 * opening the window would kick off 171 image requests at once.
 *
 * Travel is one line: `engine.processAction('travel:to', { map })`. The server
 * owns the destination tile and the validation; this window never guesses at
 * coordinates and never emits anything else.
 *
 * z-index: the marketplace's band (960-990), i.e. above the map canvas and the
 * HUD but below the RPG-JS dialog layer — and it hides itself while a game
 * dialog is up (`watchGameDialog`) instead of fighting it.
 */

import { MAP_CATALOG, REGION_LABELS, type MapCatalogEntry, type MapRegion } from './data/map-catalog'
import {
  ensureUiKit, injectStyle, el, guardKeys, pushLayer,
  makeDraggable, watchGameDialog, Z,
} from './ui-kit'

/* ================================================================= TYPES ===*/

export type RegionFilter = 'all' | MapRegion
export type MapSortKey = 'name' | 'size-desc' | 'size-asc'

interface EngineLike { processAction?: (action: string, data: unknown) => void }
interface SocketLike { on?: (type: string, cb: (data: any) => void) => void }

export interface MapBrowserApi {
  open(): void
  close(): void
  toggle(): void
  isOpen(): boolean
  /** Open the window straight onto one map's detail sheet. */
  show(mapId: string): void
  destroy(): void
  root: HTMLElement
}

