// "Create Your Character" assets: copies a curated set of Pipoya character
// sprites (via the WorkAdventure snapshot's characters/pipoya/ folder — the
// only license-clear character assets in that tree, see
// docs/woka-character-selector.md §1) into public/spritesheets/characters/
// and emits src/data/character-catalog.ts + a JSON copy for the DOM picker.
//
// Selection rule: one variant per Male/Female family number (variant "-2"
// when it exists, else the first), plus every Cat and Dog. School-themed
// sets (Student/Teacher/Headmaster) are skipped — off-theme for a trading
// floor. All sheets are 96x128 = RMSpritesheet(3,4), same as hero.png.
//
// Usage: node tools/import-characters.mjs   (from stockmonsters-mmo/)
import { readdirSync, mkdirSync, copyFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(root, '..', 'workadventure-master', 'play', 'public', 'resources', 'characters', 'pipoya')
const OUT = join(root, 'public', 'spritesheets', 'characters')
const CATALOG = join(root, 'src', 'data', 'character-catalog.ts')

mkdirSync(OUT, { recursive: true })

const files = readdirSync(SRC).filter((f) => f.endsWith('.png'))

// family map: "Male 07" -> ["Male 07-1.png", ...]
const families = new Map()
for (const f of files) {
    const m = f.match(/^(Male|Female|Cat|Dog) (\d+)-(\d+)\.png$/)
    if (!m) continue // skips Student/Teacher/Headmaster and oddballs
    const key = `${m[1]} ${m[2]}`
    if (!families.has(key)) families.set(key, [])
    families.get(key).push(f)
}

const picks = []
for (const [key, variants] of [...families.entries()].sort()) {
    variants.sort()
    const [kind, num] = key.split(' ')
    if (kind === 'Cat' || kind === 'Dog') {
        // few of them and they're all charming — take every variant
        for (const v of variants) {
            const variantNo = v.match(/-(\d+)\.png$/)[1]
            picks.push({ file: v, slug: `${kind.toLowerCase()}-${num}-${variantNo}` })
        }
    } else {
        const preferred = variants.find((v) => v.endsWith('-2.png')) ?? variants[0]
        picks.push({ file: preferred, slug: `${kind.toLowerCase()}-${num}` })
    }
}

for (const p of picks) copyFileSync(join(SRC, p.file), join(OUT, `${p.slug}.png`))

const rows = picks
    .map((p) => `    { id: 'ch-${p.slug}', image: 'spritesheets/characters/${p.slug}.png' },`)
    .join('\n')

writeFileSync(
    CATALOG,
    `// GENERATED by tools/import-characters.mjs — do not edit by hand.
// Pipoya ready-made character sheets, 96x128 = RMSpritesheet(3,4).
// No @rpgjs/* imports here: this file is shared with the Node server build.

export interface CharacterItem { id: string; image: string }

export const CHARACTER_PRESETS: CharacterItem[] = [
${rows}
]

/** Every legal character graphic id — the server-side whitelist. */
export const CHARACTER_IDS: ReadonlySet<string> = new Set(CHARACTER_PRESETS.map((i) => i.id))
`
)

// The DOM picker in index.html can't import TS — give it the same list as JSON.
const JSON_OUT = join(OUT, 'catalog.json')
writeFileSync(
    JSON_OUT,
    JSON.stringify(picks.map((p) => ({ id: `ch-${p.slug}`, image: `spritesheets/characters/${p.slug}.png` })))
)

console.log(`copied ${picks.length} sheets -> ${OUT}`)
console.log(`emitted ${CATALOG}`)
console.log(`emitted ${JSON_OUT}`)
